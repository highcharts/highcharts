/**
 * Context passed to a pivot aggregator callback, describing the cell that is
 * being aggregated.
 */
export interface PivotAggregatorContext {
    /**
     * Source column id the aggregated values come from.
     */
    columnId: string;

    /**
     * Values of the row fields leading to the cell, outermost level first. It
     * is empty for the grand total row.
     */
    rowPath: DataTableCellType[];

    /**
     * Values of the column fields leading to the cell, outermost level first.
     * It is empty for a total column.
     */
    columnPath: DataTableCellType[];

    /**
     * Whether the cell belongs to a row that subtotals its child rows.
     */
    isSubtotal: boolean;

    /**
     * Whether the cell belongs to the grand total row.
     */
    isGrandTotal: boolean;

    /**
     * Number of source rows the aggregation runs over.
     */
    rowCount: number;
}

/**
 * Aggregator option accepted by a pivot value field: a registered Formula
 * processor function name (for example `SUM`), or a callback returning one.
 */
export type PivotAggregatorOption = AggregatorOption<PivotAggregatorContext>;

/**
 * Options for a single value field, rendered as one generated column under
 * every column field value.
 */
export interface PivotValueOptions {
    /**
     * Source column id the values are taken from. A column can be used once.
     *
     * Header and cell formatting are inherited from the source column's
     * `columns[]` options, so `header.format`, `cells.format` and
     * `cells.formatter` set there apply to every generated column.
     */
    columnId: string;

    /**
     * Aggregator applied to the source rows behind every cell of the value
     * field.
     *
     * Subtotals and grand totals aggregate the source rows they cover, not the
     * values of the rows below them, so an `AVERAGE` subtotal is the average of
     * the source rows rather than an average of averages.
     *
     * @sample grid-pro/options/pivot Pivot table
     */
    aggregator: PivotAggregatorOption;
}

/**
 * Options for the pivot subtotal and grand total rows and columns.
 */
export interface PivotTotalsOptions {
    /**
     * Whether rows that have child rows aggregate the source rows below them.
     *
     * @default true
     */
    subtotals?: boolean;

    /**
     * Position of the row aggregating every source row, or `false` to omit it.
     *
     * @default 'bottom'
     */
    grandTotalRow?: ('top'|'bottom'|false);

    /**
     * Position of the column group aggregating every column field value, or
     * `false` to omit it.
     *
     * @default 'end'
     */
    grandTotalColumn?: ('start'|'end'|false);
}

/**
 * Options turning the flat source data into a pivot table, where the values of
 * the `columns` fields become generated columns and the values of the `rows`
 * fields become expandable group rows.
 *
 * A pivot requires the local data provider, and cannot be combined with
 * `treeView` or `rowGrouping`.
 *
 * @sample grid-pro/options/pivot Pivot table
 */
export interface PivotOptions {
    /**
     * Whether the pivot is applied. When `false`, the flat source data is
     * rendered instead.
     *
     * @default false
     */
    enabled?: boolean;

    /**
     * Source column ids whose values become group rows, outermost level first.
     *
     * @default []
     */
    rows?: string[];

    /**
     * Source column ids whose values become generated columns, outermost level
     * first.
     *
     * @default []
     */
    columns?: string[];

    /**
     * Value fields rendered under every column field value. At least one is
     * required.
     *
     * @sample grid-pro/options/pivot Pivot table
     */
    values: PivotValueOptions[];

    /**
     * Options for the subtotal and grand total rows and columns.
     */
    totals?: PivotTotalsOptions;
}

/**
 * Description of a column generated by the pivot, attached to the column
 * options as `pivot`.
 */
export interface PivotColumnMeta {
    /**
     * Values of the column fields the column aggregates, outermost level
     * first. It is empty for a total column.
     */
    columnPath: DataTableCellType[];

    /**
     * Source column id the aggregated values come from.
     */
    valueColumnId: string;

    /**
     * Whether the column aggregates every column field value.
     */
    isTotal: boolean;
}

/**
 * Language options for the pivot feature.
 */
export interface PivotLangOptions {
    /**
     * Header of the generated column holding the row field values, used when
     * the column has no header options configured.
     *
     * @default 'Rows'
     */
    rowsColumnHeader?: string;

    /**
     * Label of the grand total row, and header of the grand total column
     * group.
     *
     * @default 'Total'
     */
    grandTotal?: string;

    /**
     * Label rendered in place of an empty row or column field value.
     *
     * @default '(blank)'
     */
    blank?: string;
}
