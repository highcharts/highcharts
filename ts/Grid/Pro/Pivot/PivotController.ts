'use strict';


/* *
 *
 *  Imports
 *
 * */

import type DataTable from '../../../Data/DataTable';
import type Grid from '../../Core/Grid';
import type Options from '../../Core/Options';
import type { NoIdColumnOptions } from '../../Core/Table/Column';
import type { SummaryColumnOptions } from '../SummaryRows/SummaryRowsTypes';
import type {
    PivotColumnMeta,
    PivotLangOptions
} from './PivotOptions';
import type {
    PivotProjectionResult,
    ResolvedPivotOptions
} from './PivotProjection';

import PivotGlobals from './PivotGlobals.js';
import {
    PIVOT_PATH_SEPARATOR,
    PIVOT_ROWS_COLUMN_ID,
    projectPivotTable
} from './PivotProjection.js';
import { merge } from '../../../Shared/Utilities.js';


/* *
 *
 *  Class
 *
 * */

/**
 * Turns the queried table into a pivot table and takes over the root options
 * the projection needs: the header tree, the tree view input rendering the row
 * hierarchy, and the summary row holding the grand total.
 */
class PivotController {

    /* *
     *
     *  Properties
     *
     * */

    private readonly grid: Grid;

    private result?: PivotProjectionResult;

    private registeredColumnIds: string[] = [];


    /* *
     *
     *  Constructor
     *
     * */

    /**
     * Constructs the pivot controller of a Grid.
     *
     * @param grid
     * Grid the controller belongs to.
     */
    constructor(grid: Grid) {
        this.grid = grid;
    }


    /* *
     *
     *  Methods
     *
     * */

    /**
     * Returns whether a pivot layout is currently applied.
     */
    public isEnabled(): boolean {
        return !!this.result;
    }

    /**
     * Returns whether a column is generated by the pivot, so that it holds
     * aggregated values rather than source data.
     *
     * @param columnId
     * Grid column id.
     */
    public isProjectedColumn(columnId: string): boolean {
        return (
            !!this.result && (
                columnId === PIVOT_ROWS_COLUMN_ID ||
                !!this.result.columnMetaById[columnId]
            )
        );
    }

    /**
     * Returns the description of a generated column.
     *
     * @param columnId
     * Grid column id.
     *
     * @return
     * Column description, or `undefined` for a column the pivot did not
     * generate.
     */
    public getColumnMeta(columnId: string): PivotColumnMeta | undefined {
        return this.result?.columnMetaById[columnId];
    }

    /**
     * Projects the queried table into a pivot table, and applies the root
     * options the projection needs.
     *
     * @param table
     * Queried table after filtering and sorting, before pagination.
     *
     * @return
     * Projected table, or the unchanged table when the pivot is disabled.
     */
    public projectTable(table: DataTable): DataTable {
        const options = this.resolveOptions();

        if (!options) {
            this.restoreOptions();
            return table;
        }

        let result: PivotProjectionResult;

        try {
            result = projectPivotTable(table, options, this.getLang());
        } catch (error) {
            this.restoreOptions();
            // eslint-disable-next-line no-console
            console.error((error as { message?: string }).message || error);
            return table;
        }

        this.result = result;
        this.applyOptions(result, options);

        return result.table;
    }

    /**
     * Releases the options the pivot took over.
     */
    public destroy(): void {
        this.restoreOptions();
    }

    /**
     * Resolves the pivot options with their defaults, or `undefined` when the
     * pivot is disabled or cannot be applied.
     */
    private resolveOptions(): ResolvedPivotOptions | undefined {
        const options = this.grid.options?.pivot;

        if (!options?.enabled) {
            return;
        }

        // Read the user options, because an applied pivot writes a tree view
        // input of its own into the merged options.
        const userOptions = this.grid.userOptions;

        if (
            userOptions.treeView?.enabled ||
            userOptions.rowGrouping?.enabled
        ) {
            // eslint-disable-next-line no-console
            console.error(
                'Pivot: `pivot` cannot be combined with `treeView` or ' +
                '`rowGrouping`, so the pivot is ignored.'
            );
            return;
        }

        const totals = options.totals;

        return {
            rows: options.rows?.slice() || [],
            columns: options.columns?.slice() || [],
            values: options.values || [],
            subtotals: totals?.subtotals !== false,
            grandTotalRow: totals?.grandTotalRow ?? 'bottom',
            grandTotalColumn: totals?.grandTotalColumn ?? 'end'
        };
    }

    /**
     * Returns the pivot language options with their defaults.
     */
    private getLang(): PivotLangOptions {
        return this.grid.options?.lang?.pivot || {};
    }

    /**
     * Applies the root and column options of a projection.
     *
     * @param result
     * Projection result.
     *
     * @param options
     * Resolved pivot options.
     */
    private applyOptions(
        result: PivotProjectionResult,
        options: ResolvedPivotOptions
    ): void {
        const gridOptions = this.grid.options;

        if (!gridOptions) {
            return;
        }

        gridOptions.header = result.header;
        gridOptions.treeView = {
            enabled: true,
            treeColumn: PIVOT_ROWS_COLUMN_ID,
            input: {
                type: 'path',
                pathColumn: PIVOT_ROWS_COLUMN_ID,
                separator: PIVOT_PATH_SEPARATOR
            }
        };
        gridOptions.summaryRows = this.buildGrandTotalRow(result, options);

        // Tree relations live in the projected table only, not in the table of
        // the data provider the tree view reads by default.
        this.grid.treeView?.setSourceTableOverride(result.table);

        this.registerColumnOptions(result);

        // Generated columns count as unbound until the projection has run, so
        // the sorting options of a generated column are dropped when the
        // querying controller first loads them. Rebinding them here, before
        // the tree view orders the projected rows, loads them for this query.
        this.grid.columnPolicy.setAvailableSourceColumnIds(
            result.table.getColumnIds()
        );
        this.grid.querying.sorting.loadOptions();
    }

    /**
     * Builds the summary row rendering the grand total, from the values the
     * projection already aggregated.
     *
     * @param result
     * Projection result.
     *
     * @param options
     * Resolved pivot options.
     *
     * @return
     * Summary row options, or `undefined` when the grand total row is
     * disabled.
     */
    private buildGrandTotalRow(
        result: PivotProjectionResult,
        options: ResolvedPivotOptions
    ): Options['summaryRows'] {
        const grandTotalValues = result.grandTotalValues;

        if (!grandTotalValues || options.grandTotalRow === false) {
            return;
        }

        const columns: SummaryColumnOptions[] = [{
            id: PIVOT_ROWS_COLUMN_ID,
            value: this.getLang().grandTotal
        }];

        for (
            let i = 0, iEnd = result.generatedColumnIds.length;
            i < iEnd;
            ++i
        ) {
            const columnId = result.generatedColumnIds[i];

            columns.push({
                id: columnId,
                value: grandTotalValues[columnId]
            });
        }

        return {
            className: PivotGlobals.classNames.grandTotalRow,
            position: options.grandTotalRow,
            columns
        };
    }

    /**
     * Registers the options of the generated columns, inheriting the header
     * and cell formatting of the source value columns.
     *
     * @param result
     * Projection result.
     */
    private registerColumnOptions(result: PivotProjectionResult): void {
        const policy = this.grid.columnPolicy;

        // A layout change renames the generated columns, so the entries of the
        // previous one would linger in the column policy.
        for (let i = 0, iEnd = this.registeredColumnIds.length; i < iEnd; ++i) {
            policy.removeColumnOption(this.registeredColumnIds[i]);
        }
        this.registeredColumnIds = [PIVOT_ROWS_COLUMN_ID].concat(
            result.generatedColumnIds
        );

        const columnCount = policy.getColumnIds().length;

        this.setColumnOptions(PIVOT_ROWS_COLUMN_ID, {
            header: { format: this.getLang().rowsColumnHeader },
            filtering: { enabled: false }
        }, columnCount);

        for (
            let i = 0, iEnd = result.generatedColumnIds.length;
            i < iEnd;
            ++i
        ) {
            const columnId = result.generatedColumnIds[i];
            const meta = result.columnMetaById[columnId];
            const source = policy.getIndividualColumnOptions(
                meta.valueColumnId
            );

            this.setColumnOptions(columnId, {
                header: {
                    format: source?.header?.format || meta.valueColumnId
                },
                cells: source?.cells,
                className: meta.isTotal ?
                    PivotGlobals.classNames.totalColumn :
                    void 0,
                filtering: { enabled: false },
                pivot: meta
            }, columnCount + i + 1);
        }
    }

    /**
     * Stores the options of one generated column, letting a `columns[]` entry
     * the user configured for the same id win.
     *
     * @param columnId
     * Generated column id.
     *
     * @param options
     * Options inherited from the pivot layout.
     *
     * @param index
     * Position used when the column has no `columns[]` entry.
     */
    private setColumnOptions(
        columnId: string,
        options: NoIdColumnOptions,
        index: number
    ): void {
        const userColumns = this.grid.userOptions.columns;
        const userIndex = userColumns?.findIndex(
            (column): boolean => column.id === columnId
        ) ?? -1;

        this.grid.columnPolicy.setColumnOption(columnId, {
            index: userIndex > -1 ? userIndex : index,
            options: (userColumns && userIndex > -1) ?
                merge(options, userColumns[userIndex]) :
                options
        });
    }

    /**
     * Hands the root and column options the pivot took over back to the
     * options the user set.
     */
    private restoreOptions(): void {
        const grid = this.grid;
        const gridOptions = grid.options;

        delete this.result;
        grid.treeView?.setSourceTableOverride();

        if (!gridOptions) {
            return;
        }

        for (let i = 0, iEnd = this.registeredColumnIds.length; i < iEnd; ++i) {
            grid.columnPolicy.removeColumnOption(this.registeredColumnIds[i]);
        }
        this.registeredColumnIds = [];

        // `options` is merged onto the previous `options`, so the keys the
        // pivot wrote outlive it unless they are reset to what the user set.
        gridOptions.header = grid.userOptions.header;
        gridOptions.summaryRows = grid.userOptions.summaryRows;
        gridOptions.treeView = grid.userOptions.treeView;
    }

}


/* *
 *
 *  Default export
 *
 * */

export default PivotController;
